-- Откат части soft-delete-core: отметки удаления заказов стираются — мягко удалённые заказы
-- снова становятся действующими и возвращаются на доску в свою колонку на прежнюю позицию;
-- «кто, когда, почему» теряются безвозвратно. Откат выполним на любых данных (ограничений,
-- которые оживление могло бы нарушить, на tasks нет).
--
-- ВНИМАНИЕ, расхождение учёта: при удалении заказа его товар вернулся на склад (task_stock
-- пуст, движение task_return). Откат остатки НЕ пересчитывает: оживший заказ в колонке со
-- списанием (consumes_stock) стоит на доске без списанного товара, пока по нему не пройдёт
-- пересчёт — перенос карточки в другую колонку, правка состава (услуги, товары услуг) или смена
-- consumes_stock у колонки. Правка самого заказа без смены колонки остатки не пересчитывает.

DROP INDEX IF EXISTS tasks_deleted_at_idx;

ALTER TABLE tasks
    DROP CONSTRAINT IF EXISTS tasks_deleted_chk,
    DROP COLUMN delete_reason,
    DROP COLUMN deleted_by,
    DROP COLUMN deleted_at;
