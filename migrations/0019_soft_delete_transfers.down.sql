-- Откат части soft-delete-transfers: отметки удаления документов стираются — мягко удалённые
-- документы («Заявка» и «Отменён») снова становятся действующими; «кто, когда, почему» теряются
-- безвозвратно. Откат выполним на любых данных (ограничений, которые оживление могло бы
-- нарушить, на transfers нет).
--
-- ВНИМАНИЕ: при удалении заявки её единицы оборудования были освобождены
-- (active_transfer_id = NULL), откат их обратно НЕ занимает. Ожившую заявку нельзя отправить,
-- пока её не пересохранят (правка заново занимает единицы); если единица за это время попала в
-- другой документ, правка отклоняется (EQUIPMENT_IN_TRANSFER) — такую единицу придётся убрать
-- из заявки либо отменить заявку. Остатки и движения товара удаление не меняло.

DROP INDEX IF EXISTS transfers_deleted_at_idx;

ALTER TABLE transfers
    DROP CONSTRAINT IF EXISTS transfers_deleted_chk,
    DROP COLUMN delete_reason,
    DROP COLUMN deleted_by,
    DROP COLUMN deleted_at;
